def build(job):
    spec = job["scene"]
    scene = reset()
    fps = job["fps"]
    scene.render.fps = fps["num"]
    scene.render.fps_base = fps["den"]
    scene.render.resolution_x = job["width"]
    scene.render.resolution_y = job["height"]
    scene.render.resolution_percentage = max(1, int(round(job["resolutionScale"] * 100)))
    scene.frame_start = 1
    scene.frame_end = spec["durationFrames"]
    set_engine(scene, spec, job["quality"])
    setup_world(scene, spec)
    setup_bloom(scene, spec)

    objects = {}
    pending_track = []
    for o in spec["objects"]:
        kind = o["kind"]
        extra = []
        if kind == "mesh":
            obj = add_primitive(o)
            obj.name = o["name"]
        elif kind == "text":
            obj = add_text(o, job)
        elif kind == "camera":
            obj = add_camera(o)
            if o["camera"].get("trackTargetId"):
                pending_track.append((obj, o))
        elif kind == "light":
            obj = add_light(o)
        elif kind == "model":
            obj, extra = add_model(o, job)
        elif kind == "particles":
            obj = add_particles(o)
        elif kind == "media":
            obj = add_media(o, job)
        elif kind == "scatter":
            obj, source = add_scatter(o, job)
            extra = [source]
        else:
            warn(f"unknown object kind {kind}")
            continue
        if o.get("material") and kind in ("mesh", "text", "model", "scatter"):
            mat = make_material(o["name"] + " material", o["material"])
            side = (o.get("text") or {}).get("sideMaterial")
            if kind == "text" and side:
                obj = text_to_two_tone_mesh(obj, mat, make_material(o["name"] + " sides", side))
            else:
                for target in [obj] + [e for e in extra if e.type == "MESH"]:
                    assign(target, mat)
        obj.location = o["location"]
        obj.rotation_euler = [math.radians(a) for a in o["rotation"]]
        obj.scale = o["scale"]
        obj.hide_render = not o["visible"]
        if o.get("path"):
            add_path(obj, o)
        for track in o["animation"]:
            animate(obj, track)
        if kind == "camera" and o["camera"].get("shake", 0) > 0:
            add_shake(obj, o["camera"], fps["num"] / fps["den"], len(objects) + 1)
        objects[o["id"]] = obj

    for cam, o in pending_track:
        target = objects.get(o["camera"]["trackTargetId"])
        if target:
            con = cam.constraints.new("TRACK_TO")
            con.target = target
            con.track_axis = "TRACK_NEGATIVE_Z"
            con.up_axis = "UP_Y"

    cam_id = spec.get("activeCameraId")
    cam = objects.get(cam_id) if cam_id else None
    if cam is None:
        cam = next((o for o in objects.values() if o.type == "CAMERA"), None)
    if cam is None:
        raise RuntimeError("scene has no camera")
    scene.camera = cam

    transparent = spec["render"]["transparent"]
    s = scene.render.image_settings
    s.file_format = "PNG"
    s.color_mode = "RGBA" if transparent else "RGB"
    s.color_depth = "8"
    s.compression = 15
    return scene


def render_frames(scene, job):
    out_dir = job["outputDir"]
    os.makedirs(out_dir, exist_ok=True)
    frames = []
    for a, b in job["frames"]:
        frames += list(range(a, b + 1))
    total = len(frames)
    done = 0
    for f in frames:
        final = os.path.join(out_dir, f"frame_{f:05d}.png")
        if os.path.exists(final) and os.path.getsize(final) > 0:
            done += 1
            out("MANTAGLI_FRAME", f"{f} {done} {total}")
            continue
        tmp = os.path.join(out_dir, f"frame_{f:05d}.part.png")
        scene.frame_set(f)
        scene.render.filepath = tmp
        bpy.ops.render.render(write_still=True)
        if not os.path.exists(tmp):
            raise RuntimeError(f"Blender did not write frame {f}")
        os.replace(tmp, final)
        done += 1
        out("MANTAGLI_FRAME", f"{f} {done} {total}")
    return total


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    if not argv:
        raise RuntimeError("missing job file argument")
    with open(argv[0], "r", encoding="utf-8") as fh:
        job = json.load(fh)
    out("MANTAGLI_INFO", {"blender": bpy.app.version_string})
    scene = build(job)
    if job.get("saveBlend"):
        bpy.ops.wm.save_as_mainfile(filepath=job["saveBlend"], copy=True)
    total = render_frames(scene, job) if job.get("frames") else 0
    out("MANTAGLI_DONE", {"frames": total})


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:  # noqa: BLE001
        out("MANTAGLI_ERROR", {"message": str(exc), "trace": traceback.format_exc()[-3000:]})
        sys.exit(1)
