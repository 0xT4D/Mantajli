"""
Mantagli scene builder — runs inside Blender (background mode).

    blender -b --factory-startup --python-exit-code 1 -P mantagli_scene.py -- job.json

The job file is generated by the engine from a validated scene spec. This
script only interprets that structured data; it never executes code taken
from projects or assets.

stdout protocol (one per line):
    MANTAGLI_INFO {json}
    MANTAGLI_WARN <message>
    MANTAGLI_FRAME <frame> <done> <total>
    MANTAGLI_DONE {json}
    MANTAGLI_ERROR {json}
"""

import json
import math
import os
import random
import sys
import traceback

import bpy


def out(tag, payload):
    if not isinstance(payload, str):
        payload = json.dumps(payload)
    print(f"{tag} {payload}", flush=True)


def warn(msg):
    out("MANTAGLI_WARN", msg)


def hex_rgb(h):
    h = h.lstrip("#")
    srgb = [int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4)]
    # Blender colour sockets are linear.
    return [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in srgb]


def rgba(h, a=1.0):
    return (*hex_rgb(h), a)


# ------------------------------------------------------------------ scene setup


def reset():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    return bpy.context.scene


def set_engine(scene, spec, quality):
    r = spec["render"]
    engine = {"eevee": "BLENDER_EEVEE", "cycles": "CYCLES", "workbench": "BLENDER_WORKBENCH"}[r["engine"]]
    try:
        scene.render.engine = engine
    except TypeError:
        scene.render.engine = "BLENDER_EEVEE_NEXT"
    draft = quality == "draft"
    samples = r["samples"]
    if draft:
        samples = max(1, min(samples, 12 if engine != "CYCLES" else 16))
    if scene.render.engine.startswith("BLENDER_EEVEE"):
        scene.eevee.taa_render_samples = samples
        if hasattr(scene.eevee, "use_raytracing"):
            scene.eevee.use_raytracing = bool(r.get("raytracing", False)) and not draft
    elif engine == "CYCLES":
        scene.cycles.samples = samples
        scene.cycles.use_denoising = bool(r["denoise"])
        enable_gpu(scene)
    scene.render.use_motion_blur = bool(r["motionBlur"])
    scene.render.motion_blur_shutter = r["shutter"]
    scene.render.film_transparent = bool(r["transparent"])

    vs = scene.view_settings
    try:
        vs.view_transform = r["viewTransform"]
    except TypeError:
        warn(f"view transform {r['viewTransform']} unavailable")
    look = r.get("look", "None")
    if look != "None":
        for candidate in (f"{r['viewTransform']} - {look}", look):
            try:
                vs.look = candidate
                break
            except TypeError:
                continue
        else:
            warn(f"look {look} unavailable")


def enable_gpu(scene):
    try:
        prefs = bpy.context.preferences.addons["cycles"].preferences
        for backend in ("OPTIX", "CUDA", "HIP", "METAL", "ONEAPI"):
            try:
                prefs.compute_device_type = backend
                prefs.get_devices()
                devs = [d for d in prefs.devices if d.type == backend]
                if devs:
                    for d in prefs.devices:
                        d.use = d.type == backend
                    scene.cycles.device = "GPU"
                    out("MANTAGLI_INFO", {"cyclesDevice": backend})
                    return
            except TypeError:
                continue
    except Exception as e:  # noqa: BLE001
        warn(f"GPU setup failed, using CPU: {e}")
    scene.cycles.device = "CPU"


def setup_world(scene, spec):
    w = spec["world"]
    world = bpy.data.worlds.new("World")
    scene.world = world
    world.use_nodes = True
    nt = world.node_tree
    bg = nt.nodes.get("Background")
    bg.inputs["Color"].default_value = rgba(w["color"])
    bg.inputs["Strength"].default_value = w["strength"]
    refl = w.get("reflections", 0)
    if refl > 0:
        # Camera rays see the plain background; every other ray (reflections,
        # world lighting probes) sees a soft bright band around the horizon.
        nodes, links = nt.nodes, nt.links
        out_node = nodes.get("World Output")
        lp = nodes.new("ShaderNodeLightPath")
        tc = nodes.new("ShaderNodeTexCoord")
        sep = nodes.new("ShaderNodeSeparateXYZ")
        absz = nodes.new("ShaderNodeMath")
        absz.operation = "ABSOLUTE"
        band = nodes.new("ShaderNodeMapRange")
        band.interpolation_type = "SMOOTHSTEP"
        band.inputs["From Min"].default_value = 0.0
        band.inputs["From Max"].default_value = 0.4
        band.inputs["To Min"].default_value = refl
        band.inputs["To Max"].default_value = 0.0
        studio = nodes.new("ShaderNodeBackground")
        studio.inputs["Color"].default_value = (0.95, 0.96, 1.0, 1.0)
        mix = nodes.new("ShaderNodeMixShader")
        links.new(tc.outputs["Generated"], sep.inputs["Vector"])
        links.new(sep.outputs["Z"], absz.inputs[0])
        links.new(absz.outputs["Value"], band.inputs["Value"])
        links.new(band.outputs["Result"], studio.inputs["Strength"])
        links.new(lp.outputs["Is Camera Ray"], mix.inputs["Fac"])
        links.new(studio.outputs["Background"], mix.inputs[1])
        links.new(bg.outputs["Background"], mix.inputs[2])
        links.new(mix.outputs["Shader"], out_node.inputs["Surface"])
    if w["fog"] > 0:
        vol = nt.nodes.new("ShaderNodeVolumePrincipled")
        vol.inputs["Density"].default_value = w["fog"] * 0.06
        out_node = nt.nodes.get("World Output")
        nt.links.new(vol.outputs["Volume"], out_node.inputs["Volume"])


def setup_bloom(scene, spec):
    """Bloom through the compositor Glare node (EEVEE has no built-in bloom since 4.2)."""
    if not spec["render"]["bloom"]:
        return
    new_api = hasattr(scene, "compositing_node_group")
    tree = None
    try:
        if new_api:
            # Blender 5.x: compositor is a node group with an Image output.
            tree = bpy.data.node_groups.new("Mantagli Compositor", "CompositorNodeTree")
            tree.interface.new_socket("Image", in_out="OUTPUT", socket_type="NodeSocketColor")
            out_node = tree.nodes.new("NodeGroupOutput")
        else:
            scene.use_nodes = True
            tree = scene.node_tree
            tree.nodes.clear()
            out_node = tree.nodes.new("CompositorNodeComposite")
        rl = tree.nodes.new("CompositorNodeRLayers")
        glare = tree.nodes.new("CompositorNodeGlare")
        if "Type" in glare.inputs:  # 4.4+: menu socket
            glare.inputs["Type"].default_value = "Bloom"
        else:
            glare.glare_type = "BLOOM" if "BLOOM" in glare.bl_rna.properties["glare_type"].enum_items.keys() else "FOG_GLOW"
            glare.threshold = 0.9
        for name, val in (("Threshold", 0.85), ("Strength", 0.5), ("Size", 0.55), ("Quality", "High")):
            if name in glare.inputs:
                glare.inputs[name].default_value = val
        tree.links.new(rl.outputs["Image"], glare.inputs["Image"])
        tree.links.new(glare.outputs["Image"], out_node.inputs[0])
        # Attach only once fully linked, so a failure never blanks the render.
        if new_api:
            scene.compositing_node_group = tree
        if hasattr(scene.render, "use_compositing"):
            scene.render.use_compositing = True
    except Exception as e:  # noqa: BLE001
        warn(f"bloom unavailable: {e}")
        if new_api:
            scene.compositing_node_group = None
            if tree is not None:
                bpy.data.node_groups.remove(tree)
        elif hasattr(scene, "use_nodes"):
            scene.use_nodes = False


# ------------------------------------------------------------------ materials

PRESETS = {
    "chrome": dict(metallic=1.0, roughness=0.06),
    "gold": dict(metallic=1.0, roughness=0.18, base="#ffc356"),
    "glass": dict(metallic=0.0, roughness=0.0, transmission=1.0),
    "matte": dict(metallic=0.0, roughness=0.9),
    "plastic": dict(metallic=0.0, roughness=0.35),
    "neon": dict(metallic=0.0, roughness=0.5, emission=True),
    "carPaint": dict(metallic=0.5, roughness=0.2, coat=1.0),
}


def set_input(node, names, value):
    for n in names:
        if n in node.inputs:
            node.inputs[n].default_value = value
            return True
    return False


def make_material(name, m):
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    preset = PRESETS.get(m.get("preset", "custom"), {})
    base = preset.get("base", m["baseColor"]) if m.get("preset") == "gold" else m["baseColor"]
    set_input(bsdf, ["Base Color"], rgba(base))
    set_input(bsdf, ["Metallic"], preset.get("metallic", m["metallic"]))
    set_input(bsdf, ["Roughness"], preset.get("roughness", m["roughness"]))
    trans = preset.get("transmission", m.get("transmission", 0.0))
    set_input(bsdf, ["Transmission Weight", "Transmission"], trans)
    if preset.get("coat"):
        set_input(bsdf, ["Coat Weight", "Clearcoat"], preset["coat"])
    if m["emissionStrength"] > 0:
        set_input(bsdf, ["Emission Color", "Emission"], rgba(m["emissionColor"]))
        set_input(bsdf, ["Emission Strength"], m["emissionStrength"])
    return mat


def assign(obj, mat):
    if obj.type in {"MESH", "CURVE", "FONT", "SURFACE", "META"}:
        obj.data.materials.clear()
        obj.data.materials.append(mat)


# ------------------------------------------------------------------ objects


def link(obj):
    bpy.context.scene.collection.objects.link(obj)
    return obj


def add_primitive(spec):
    prim = spec["mesh"]["primitive"]
    size = spec["mesh"]["size"]
    ops = bpy.ops.mesh
    if prim in ("cube", "roundedCube"):
        ops.primitive_cube_add(size=size)
    elif prim == "sphere":
        ops.primitive_uv_sphere_add(radius=size / 2, segments=64, ring_count=32)
    elif prim == "plane":
        ops.primitive_plane_add(size=size)
    elif prim == "cylinder":
        ops.primitive_cylinder_add(radius=size / 2, depth=size, vertices=64)
    elif prim == "cone":
        ops.primitive_cone_add(radius1=size / 2, depth=size, vertices=64)
    elif prim == "torus":
        ops.primitive_torus_add(major_radius=size / 2, minor_radius=size / 6, major_segments=64, minor_segments=24)
    elif prim == "monkey":
        ops.primitive_monkey_add(size=size)
    obj = bpy.context.active_object
    if prim == "roundedCube":
        bev = obj.modifiers.new("Bevel", "BEVEL")
        bev.width = size * 0.12
        bev.segments = 6
    if prim == "monkey":
        obj.modifiers.new("Subdivision", "SUBSURF").levels = 2
    if spec["mesh"]["smooth"] and prim not in ("cube", "plane"):
        for p in obj.data.polygons:
            p.use_smooth = True
    return obj


def add_text(spec, job):
    t = spec["text"]
    curve = bpy.data.curves.new(spec["name"], type="FONT")
    curve.body = t["body"]
    curve.size = t["size"]
    curve.extrude = t["extrude"]
    curve.bevel_depth = t["bevel"]
    curve.bevel_resolution = 4
    curve.align_x = {"left": "LEFT", "center": "CENTER", "right": "RIGHT"}[t["align"]]
    curve.align_y = "CENTER"
    curve.space_character = t["letterSpacing"]
    font_path = job["fonts"].get(t.get("fontAssetId") or "", job.get("defaultFont"))
    if font_path and os.path.exists(font_path):
        try:
            curve.font = bpy.data.fonts.load(font_path, check_existing=True)
        except RuntimeError as e:
            warn(f"font load failed: {e}")
    return link(bpy.data.objects.new(spec["name"], curve))


def add_camera(spec):
    c = spec["camera"]
    cam = bpy.data.cameras.new(spec["name"])
    cam.lens = c["focalLength"]
    cam.clip_end = 1000
    cam.dof.use_dof = c["dof"]
    cam.dof.focus_distance = c["focusDistance"]
    cam.dof.aperture_fstop = c["fStop"]
    return link(bpy.data.objects.new(spec["name"], cam))


def add_light(spec):
    l = spec["light"]
    light = bpy.data.lights.new(spec["name"], type=l["type"].upper())
    light.color = hex_rgb(l["color"])
    light.energy = l["energy"]
    if l["type"] == "area":
        light.size = max(0.01, l["size"])
    elif l["type"] in ("point", "spot"):
        light.shadow_soft_size = l["size"]
    elif l["type"] == "sun":
        light.angle = math.radians(max(0.0, min(180.0, l["size"])))
    return link(bpy.data.objects.new(spec["name"], light))


IMPORTERS = {
    ".glb": lambda p: bpy.ops.import_scene.gltf(filepath=p),
    ".gltf": lambda p: bpy.ops.import_scene.gltf(filepath=p),
    ".obj": lambda p: bpy.ops.wm.obj_import(filepath=p),
    ".fbx": lambda p: bpy.ops.import_scene.fbx(filepath=p),
    ".stl": lambda p: bpy.ops.wm.stl_import(filepath=p),
    ".ply": lambda p: bpy.ops.wm.ply_import(filepath=p),
}


def add_model(spec, job):
    path = job["assets"].get(spec["model"]["assetId"])
    if not path or not os.path.exists(path):
        raise RuntimeError(f"model file missing for {spec['name']}")
    ext = os.path.splitext(path)[1].lower()
    if ext not in IMPORTERS:
        raise RuntimeError(f"unsupported model format {ext}")
    before = set(bpy.data.objects)
    IMPORTERS[ext](path)
    imported = [o for o in bpy.data.objects if o not in before]
    root = link(bpy.data.objects.new(spec["name"], None))
    # Normalise: fit the model in a 2-unit cube centred on the origin.
    from mathutils import Vector

    pts = []
    for o in imported:
        if o.type == "MESH":
            pts += [o.matrix_world @ Vector(c) for c in o.bound_box]
    for o in imported:
        if o.parent is None:
            o.parent = root
    if pts:
        mn = Vector((min(p.x for p in pts), min(p.y for p in pts), min(p.z for p in pts)))
        mx = Vector((max(p.x for p in pts), max(p.y for p in pts), max(p.z for p in pts)))
        size = max((mx - mn).x, (mx - mn).y, (mx - mn).z) or 1.0
        centre = (mn + mx) / 2
        holder = link(bpy.data.objects.new(spec["name"] + " fit", None))
        holder.parent = root
        for o in imported:
            if o.parent == root:
                o.parent = holder
        holder.scale = (2.0 / size,) * 3
        holder.location = -centre * (2.0 / size)
    return root, imported


def add_particles(spec):
    p = spec["particles"]
    rnd = random.Random(p["seed"])
    ax, ay, az = p["area"]
    verts = [(rnd.uniform(-ax, ax), rnd.uniform(-ay, ay), rnd.uniform(-az, az)) for _ in range(p["count"])]
    mesh = bpy.data.meshes.new(spec["name"] + " points")
    mesh.from_pydata(verts, [], [])
    emitter = link(bpy.data.objects.new(spec["name"], mesh))
    bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=1, radius=p["size"])
    mote = bpy.context.active_object
    mote.name = spec["name"] + " mote"
    mat = make_material(
        spec["name"] + " mat",
        {"preset": "custom", "baseColor": p["color"], "metallic": 0, "roughness": 1, "emissionColor": p["color"], "emissionStrength": p["emission"]},
    )
    assign(mote, mat)
    mote.parent = emitter
    emitter.instance_type = "VERTS"
    return emitter


# ------------------------------------------------------------------ animation

INTERP = {
    "linear": ("LINEAR", "AUTO"),
    "hold": ("CONSTANT", "AUTO"),
    "easeIn": ("QUAD", "EASE_IN"),
    "easeOut": ("QUAD", "EASE_OUT"),
    "easeInOut": ("BEZIER", "AUTO"),
}


def fcurves_of(idblock):
    ad = idblock.animation_data
    if not ad or not ad.action:
        return []
    act = ad.action
    try:
        return list(act.fcurves)
    except AttributeError:
        pass
    curves = []
    for layer in getattr(act, "layers", []):
        for strip in layer.strips:
            bag = strip.channelbag(ad.action_slot) if ad.action_slot else None
            if bag:
                curves += list(bag.fcurves)
    return curves


def animate(obj, track):
    prop = track["property"]
    target, path = obj, None
    if prop == "location":
        path = "location"
    elif prop == "rotation":
        path = "rotation_euler"
    elif prop == "scale":
        path = "scale"
    elif prop == "focalLength":
        target, path = obj.data, "lens"
    elif prop == "focusDistance":
        target, path = obj.data.dof, "focus_distance"
    elif prop == "energy":
        target, path = obj.data, "energy"
    easing_by_frame = {}
    for k in track["keyframes"]:
        frame = k["frame"] + 1
        v = k["value"]
        if prop == "rotation":
            setattr(target, path, [math.radians(x) for x in v])
        elif len(v) == 3:
            setattr(target, path, v)
        else:
            setattr(target, path, v[0])
        target.keyframe_insert(data_path=path, frame=frame)
        easing_by_frame[frame] = INTERP.get(k.get("easing", "easeInOut"), INTERP["easeInOut"])
    # Camera/light data properties keep their animation on the data block.
    owner = obj if target is obj else obj.data
    for fc in fcurves_of(owner):
        for kp in fc.keyframe_points:
            interp = easing_by_frame.get(int(round(kp.co.x)))
            if interp:
                kp.interpolation, kp.easing = interp


# ------------------------------------------------------------------ build


def build(job):
    spec = job["scene"]
    scene = reset()
    fps = job["fps"]
    scene.render.fps = fps["num"]
    scene.render.fps_base = fps["den"]
    scene.render.resolution_x = job["width"]
    scene.render.resolution_y = job["height"]
    scene.render.resolution_percentage = max(1, int(round(job["resolutionScale"] * 100)))
    scene.frame_start = 1
    scene.frame_end = spec["durationFrames"]
    set_engine(scene, spec, job["quality"])
    setup_world(scene, spec)
    setup_bloom(scene, spec)

    objects = {}
    pending_track = []
    for o in spec["objects"]:
        kind = o["kind"]
        extra = []
        if kind == "mesh":
            obj = add_primitive(o)
            obj.name = o["name"]
        elif kind == "text":
            obj = add_text(o, job)
        elif kind == "camera":
            obj = add_camera(o)
            if o["camera"].get("trackTargetId"):
                pending_track.append((obj, o))
        elif kind == "light":
            obj = add_light(o)
        elif kind == "model":
            obj, extra = add_model(o, job)
        elif kind == "particles":
            obj = add_particles(o)
        else:
            warn(f"unknown object kind {kind}")
            continue
        obj.location = o["location"]
        obj.rotation_euler = [math.radians(a) for a in o["rotation"]]
        obj.scale = o["scale"]
        obj.hide_render = not o["visible"]
        if o.get("material") and kind in ("mesh", "text", "model"):
            mat = make_material(o["name"] + " material", o["material"])
            for target in [obj] + [e for e in extra if e.type == "MESH"]:
                assign(target, mat)
        for track in o["animation"]:
            animate(obj, track)
        objects[o["id"]] = obj

    for cam, o in pending_track:
        target = objects.get(o["camera"]["trackTargetId"])
        if target:
            con = cam.constraints.new("TRACK_TO")
            con.target = target
            con.track_axis = "TRACK_NEGATIVE_Z"
            con.up_axis = "UP_Y"

    cam_id = spec.get("activeCameraId")
    cam = objects.get(cam_id) if cam_id else None
    if cam is None:
        cam = next((o for o in objects.values() if o.type == "CAMERA"), None)
    if cam is None:
        raise RuntimeError("scene has no camera")
    scene.camera = cam

    transparent = spec["render"]["transparent"]
    s = scene.render.image_settings
    s.file_format = "PNG"
    s.color_mode = "RGBA" if transparent else "RGB"
    s.color_depth = "8"
    s.compression = 15
    return scene


def render_frames(scene, job):
    out_dir = job["outputDir"]
    os.makedirs(out_dir, exist_ok=True)
    frames = []
    for a, b in job["frames"]:
        frames += list(range(a, b + 1))
    total = len(frames)
    done = 0
    for f in frames:
        final = os.path.join(out_dir, f"frame_{f:05d}.png")
        if os.path.exists(final) and os.path.getsize(final) > 0:
            done += 1
            out("MANTAGLI_FRAME", f"{f} {done} {total}")
            continue
        tmp = os.path.join(out_dir, f"frame_{f:05d}.part.png")
        scene.frame_set(f)
        scene.render.filepath = tmp
        bpy.ops.render.render(write_still=True)
        if not os.path.exists(tmp):
            raise RuntimeError(f"Blender did not write frame {f}")
        os.replace(tmp, final)
        done += 1
        out("MANTAGLI_FRAME", f"{f} {done} {total}")
    return total


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    if not argv:
        raise RuntimeError("missing job file argument")
    with open(argv[0], "r", encoding="utf-8") as fh:
        job = json.load(fh)
    out("MANTAGLI_INFO", {"blender": bpy.app.version_string})
    scene = build(job)
    if job.get("saveBlend"):
        bpy.ops.wm.save_as_mainfile(filepath=job["saveBlend"], copy=True)
    total = render_frames(scene, job) if job.get("frames") else 0
    out("MANTAGLI_DONE", {"frames": total})


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:  # noqa: BLE001
        out("MANTAGLI_ERROR", {"message": str(exc), "trace": traceback.format_exc()[-3000:]})
        sys.exit(1)
