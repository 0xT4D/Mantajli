"""
Mantagli scene builder — runs inside Blender (background mode).

    blender -b --factory-startup --python-exit-code 1 -P mantagli_scene.py -- job.json

The job file is generated by the engine from a validated scene spec. This
script only interprets that structured data; it never executes code taken
from projects or assets.

stdout protocol (one per line):
    MANTAGLI_INFO {json}
    MANTAGLI_WARN <message>
    MANTAGLI_FRAME <frame> <done> <total>
    MANTAGLI_DONE {json}
    MANTAGLI_ERROR {json}
"""

import json
import math
import os
import random
import sys
import traceback

import bpy


def out(tag, payload):
    if not isinstance(payload, str):
        payload = json.dumps(payload)
    print(f"{tag} {payload}", flush=True)


def warn(msg):
    out("MANTAGLI_WARN", msg)


def hex_rgb(h):
    h = h.lstrip("#")
    srgb = [int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4)]
    # Blender colour sockets are linear.
    return [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in srgb]


def rgba(h, a=1.0):
    return (*hex_rgb(h), a)


# ------------------------------------------------------------------ scene setup


def reset():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    return bpy.context.scene


def set_engine(scene, spec, quality):
    r = spec["render"]
    engine = {"eevee": "BLENDER_EEVEE", "cycles": "CYCLES", "workbench": "BLENDER_WORKBENCH"}[r["engine"]]
    try:
        scene.render.engine = engine
    except TypeError:
        scene.render.engine = "BLENDER_EEVEE_NEXT"
    draft = quality == "draft"
    samples = r["samples"]
    if draft:
        samples = max(1, min(samples, 12 if engine != "CYCLES" else 16))
    if scene.render.engine.startswith("BLENDER_EEVEE"):
        scene.eevee.taa_render_samples = samples
        if hasattr(scene.eevee, "use_raytracing"):
            scene.eevee.use_raytracing = bool(r.get("raytracing", False)) and not draft
    elif engine == "CYCLES":
        scene.cycles.samples = samples
        scene.cycles.use_denoising = bool(r["denoise"])
        enable_gpu(scene)
    scene.render.use_motion_blur = bool(r["motionBlur"])
    scene.render.motion_blur_shutter = r["shutter"]
    scene.render.film_transparent = bool(r["transparent"])

    vs = scene.view_settings
    try:
        vs.view_transform = r["viewTransform"]
    except TypeError:
        warn(f"view transform {r['viewTransform']} unavailable")
    look = r.get("look", "None")
    if look != "None":
        for candidate in (f"{r['viewTransform']} - {look}", look):
            try:
                vs.look = candidate
                break
            except TypeError:
                continue
        else:
            warn(f"look {look} unavailable")


def enable_gpu(scene):
    try:
        prefs = bpy.context.preferences.addons["cycles"].preferences
        for backend in ("OPTIX", "CUDA", "HIP", "METAL", "ONEAPI"):
            try:
                prefs.compute_device_type = backend
                prefs.get_devices()
                devs = [d for d in prefs.devices if d.type == backend]
                if devs:
                    for d in prefs.devices:
                        d.use = d.type == backend
                    scene.cycles.device = "GPU"
                    out("MANTAGLI_INFO", {"cyclesDevice": backend})
                    return
            except TypeError:
                continue
    except Exception as e:  # noqa: BLE001
        warn(f"GPU setup failed, using CPU: {e}")
    scene.cycles.device = "CPU"
    out("MANTAGLI_INFO", {"cyclesDevice": "CPU"})


def setup_world(scene, spec):
    w = spec["world"]
    world = bpy.data.worlds.new("World")
    scene.world = world
    world.use_nodes = True
    nt = world.node_tree
    bg = nt.nodes.get("Background")
    bg.inputs["Color"].default_value = rgba(w["color"])
    bg.inputs["Strength"].default_value = w["strength"]
    refl = w.get("reflections", 0)
    if refl > 0:
        # Camera rays see the plain background; every other ray (reflections,
        # world lighting probes) sees a soft bright band around the horizon.
        nodes, links = nt.nodes, nt.links
        out_node = nodes.get("World Output")
        lp = nodes.new("ShaderNodeLightPath")
        tc = nodes.new("ShaderNodeTexCoord")
        sep = nodes.new("ShaderNodeSeparateXYZ")
        absz = nodes.new("ShaderNodeMath")
        absz.operation = "ABSOLUTE"
        band = nodes.new("ShaderNodeMapRange")
        band.interpolation_type = "SMOOTHSTEP"
        band.inputs["From Min"].default_value = 0.0
        band.inputs["From Max"].default_value = 0.4
        band.inputs["To Min"].default_value = refl
        band.inputs["To Max"].default_value = 0.0
        studio = nodes.new("ShaderNodeBackground")
        studio.inputs["Color"].default_value = (0.95, 0.96, 1.0, 1.0)
        mix = nodes.new("ShaderNodeMixShader")
        links.new(tc.outputs["Generated"], sep.inputs["Vector"])
        links.new(sep.outputs["Z"], absz.inputs[0])
        links.new(absz.outputs["Value"], band.inputs["Value"])
        links.new(band.outputs["Result"], studio.inputs["Strength"])
        links.new(lp.outputs["Is Camera Ray"], mix.inputs["Fac"])
        links.new(studio.outputs["Background"], mix.inputs[1])
        links.new(bg.outputs["Background"], mix.inputs[2])
        links.new(mix.outputs["Shader"], out_node.inputs["Surface"])
    if w["fog"] > 0:
        vol = nt.nodes.new("ShaderNodeVolumePrincipled")
        vol.inputs["Density"].default_value = w["fog"] * 0.06
        out_node = nt.nodes.get("World Output")
        nt.links.new(vol.outputs["Volume"], out_node.inputs["Volume"])


def setup_bloom(scene, spec):
    """Bloom through the compositor Glare node (EEVEE has no built-in bloom since 4.2)."""
    if not spec["render"]["bloom"]:
        return
    new_api = hasattr(scene, "compositing_node_group")
    tree = None
    try:
        if new_api:
            # Blender 5.x: compositor is a node group with an Image output.
            tree = bpy.data.node_groups.new("Mantagli Compositor", "CompositorNodeTree")
            tree.interface.new_socket("Image", in_out="OUTPUT", socket_type="NodeSocketColor")
            out_node = tree.nodes.new("NodeGroupOutput")
        else:
            scene.use_nodes = True
            tree = scene.node_tree
            tree.nodes.clear()
            out_node = tree.nodes.new("CompositorNodeComposite")
        rl = tree.nodes.new("CompositorNodeRLayers")
        glare = tree.nodes.new("CompositorNodeGlare")
        if "Type" in glare.inputs:  # 4.4+: menu socket
            glare.inputs["Type"].default_value = "Bloom"
        else:
            glare.glare_type = "BLOOM" if "BLOOM" in glare.bl_rna.properties["glare_type"].enum_items.keys() else "FOG_GLOW"
            glare.threshold = 0.9
        for name, val in (("Threshold", 0.85), ("Strength", 0.5), ("Size", 0.55), ("Quality", "High")):
            if name in glare.inputs:
                glare.inputs[name].default_value = val
        tree.links.new(rl.outputs["Image"], glare.inputs["Image"])
        tree.links.new(glare.outputs["Image"], out_node.inputs[0])
        # Attach only once fully linked, so a failure never blanks the render.
        if new_api:
            scene.compositing_node_group = tree
        if hasattr(scene.render, "use_compositing"):
            scene.render.use_compositing = True
    except Exception as e:  # noqa: BLE001
        warn(f"bloom unavailable: {e}")
        if new_api:
            scene.compositing_node_group = None
            if tree is not None:
                bpy.data.node_groups.remove(tree)
        elif hasattr(scene, "use_nodes"):
            scene.use_nodes = False


